-- DDE Telecom V11 — esquema idempotente para PostgreSQL.
-- Não apaga tabelas nem dados existentes. Faça backup antes de aplicar mudanças.
BEGIN;

CREATE TABLE IF NOT EXISTS public.usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(120) NOT NULL,
    email varchar(150) NOT NULL,
    senha_hash varchar(255) NOT NULL,
    perfil varchar(30) NOT NULL DEFAULT 'vendedor',
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamp without time zone NOT NULL DEFAULT now(),
    atualizado_em timestamp without time zone NOT NULL DEFAULT now()
);
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS nome varchar(120);
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS email varchar(150);
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS senha_hash varchar(255);
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS perfil varchar(30) NOT NULL DEFAULT 'vendedor';
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS ativo boolean NOT NULL DEFAULT true;
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS criado_em timestamp without time zone NOT NULL DEFAULT now();
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS atualizado_em timestamp without time zone NOT NULL DEFAULT now();
CREATE UNIQUE INDEX IF NOT EXISTS usuarios_email_lower_uidx ON public.usuarios (lower(email));

CREATE TABLE IF NOT EXISTS public.planos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(150) NOT NULL,
    tipo varchar(50) NOT NULL,
    velocidade varchar(50),
    franquia varchar(50),
    preco numeric(10,2) NOT NULL CHECK (preco >= 0),
    descricao text,
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    destaque boolean NOT NULL DEFAULT false,
    selo varchar(100),
    ordem integer NOT NULL DEFAULT 0 CHECK (ordem >= 0),
    beneficios jsonb NOT NULL DEFAULT '[]'::jsonb,
    fidelidade_meses integer,
    preco_original numeric(10,2),
    promocional boolean NOT NULL DEFAULT false,
    oferta_valida_ate date,
    observacoes text,
    atualizado_em timestamp with time zone NOT NULL DEFAULT now()
);
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS nome varchar(150);
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS tipo varchar(50);
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS velocidade varchar(50);
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS franquia varchar(50);
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS preco numeric(10,2);
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS descricao text;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS ativo boolean NOT NULL DEFAULT true;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS criado_em timestamp without time zone DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS destaque boolean NOT NULL DEFAULT false;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS selo varchar(100);
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS ordem integer NOT NULL DEFAULT 0;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS beneficios jsonb NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS fidelidade_meses integer;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS preco_original numeric(10,2);
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS promocional boolean NOT NULL DEFAULT false;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS oferta_valida_ate date;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS observacoes text;
ALTER TABLE public.planos ADD COLUMN IF NOT EXISTS atualizado_em timestamp with time zone NOT NULL DEFAULT now();
ALTER TABLE public.planos ALTER COLUMN nome TYPE varchar(150);
ALTER TABLE public.planos ALTER COLUMN selo TYPE varchar(100);
CREATE INDEX IF NOT EXISTS idx_planos_tipo_ativo_ordem ON public.planos(tipo, ativo, ordem);

CREATE TABLE IF NOT EXISTS public.leads (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(150) NOT NULL,
    telefone varchar(20) NOT NULL,
    email varchar(150),
    cep varchar(9),
    interesse varchar(100),
    status varchar(30) DEFAULT 'novo',
    origem varchar(50) DEFAULT 'site',
    metadados_marketing jsonb NOT NULL DEFAULT '{}'::jsonb,
    criado_em timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    logradouro varchar(150),
    numero varchar(20),
    complemento varchar(100),
    bairro varchar(100),
    cidade varchar(100),
    estado varchar(2),
    observacoes text,
    ultimo_contato timestamp without time zone,
    vendedor varchar(120),
    vendedor_id integer REFERENCES public.usuarios(id) ON DELETE SET NULL
);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS nome varchar(150);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS telefone varchar(20);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS email varchar(150);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS cep varchar(9);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS interesse varchar(100);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS status varchar(30) DEFAULT 'novo';
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS origem varchar(50) DEFAULT 'site';
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS metadados_marketing jsonb NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS criado_em timestamp without time zone DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS logradouro varchar(150);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS numero varchar(20);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS complemento varchar(100);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS bairro varchar(100);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS cidade varchar(100);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS estado varchar(2);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS observacoes text;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS ultimo_contato timestamp without time zone;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS vendedor varchar(120);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS vendedor_id integer;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS excluido_em timestamp with time zone;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS excluido_por integer;
CREATE INDEX IF NOT EXISTS idx_leads_status ON public.leads(status);
CREATE INDEX IF NOT EXISTS idx_leads_telefone ON public.leads(telefone);
CREATE INDEX IF NOT EXISTS idx_leads_vendedor_id ON public.leads(vendedor_id);
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'leads_vendedor_id_fkey' AND conrelid = 'public.leads'::regclass) THEN
        ALTER TABLE public.leads ADD CONSTRAINT leads_vendedor_id_fkey
            FOREIGN KEY (vendedor_id) REFERENCES public.usuarios(id) ON DELETE SET NULL NOT VALID;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.meta_lead_imports (
    meta_lead_id varchar(120) PRIMARY KEY,
    page_id varchar(120) NOT NULL,
    form_id varchar(120),
    ad_id varchar(120),
    adgroup_id varchar(120),
    meta_created_time bigint,
    status varchar(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'processing', 'processed', 'needs_review', 'failed')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at timestamp with time zone NOT NULL DEFAULT now(),
    last_error_code varchar(80),
    lead_id integer REFERENCES public.leads(id) ON DELETE SET NULL,
    received_at timestamp with time zone NOT NULL DEFAULT now(),
    processed_at timestamp with time zone,
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_meta_lead_imports_pending
    ON public.meta_lead_imports(status, next_attempt_at, received_at);

-- Tabelas auxiliares mantidas do esquema original.
CREATE TABLE IF NOT EXISTS public.clientes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(150) NOT NULL,
    cpf varchar(14),
    email varchar(150),
    telefone varchar(20) NOT NULL,
    data_nascimento date,
    criado_em timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.enderecos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id integer REFERENCES public.clientes(id) ON DELETE CASCADE,
    cep varchar(9) NOT NULL,
    logradouro varchar(150),
    numero varchar(20),
    complemento varchar(100),
    bairro varchar(100),
    cidade varchar(100),
    estado varchar(2),
    criado_em timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.pedidos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id integer REFERENCES public.clientes(id),
    plano_id integer REFERENCES public.planos(id),
    status varchar(30) DEFAULT 'pendente',
    observacoes text,
    criado_em timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_clientes_cpf ON public.clientes(cpf);
CREATE INDEX IF NOT EXISTS idx_pedidos_status ON public.pedidos(status);

CREATE OR REPLACE FUNCTION public.atualizar_data_planos() RETURNS trigger
LANGUAGE plpgsql AS $$ BEGIN NEW.atualizado_em = now(); RETURN NEW; END; $$;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_planos_atualizado_em' AND tgrelid = 'public.planos'::regclass) THEN
        CREATE TRIGGER trg_planos_atualizado_em BEFORE UPDATE ON public.planos
            FOR EACH ROW EXECUTE FUNCTION public.atualizar_data_planos();
    END IF;
END $$;

COMMIT;
